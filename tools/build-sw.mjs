// Generates sw.js: precaches every app file so the app works in airplane mode. Run after any file change: node tools/build-sw.mjs
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKIP = new Set(['sw.js', 'package.json', 'package-lock.json', 'vercel.json', '.gitignore', 'README.md']);
const SKIPDIR = new Set(['tools', 'node_modules', '.git', 'test', 'docs', 'android-app']);
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name), rel = path.relative(ROOT, p).split(path.sep).join('/');
    if (e.isDirectory()) { if (!SKIPDIR.has(e.name)) walk(p); } else if (!SKIP.has(rel) && !e.name.startsWith('.')) files.push(rel);
  }
})(ROOT);
files.sort();
const h = crypto.createHash('sha256'); for (const f of files) { h.update(f); h.update(fs.readFileSync(path.join(ROOT, f))); }
const version = h.digest('hex').slice(0, 12);
if (process.argv.includes('--check')) { const cur = fs.readFileSync(path.join(ROOT, 'sw.js'), 'utf8'); if (!cur.includes("'demi-plank-" + version + "'")) { console.error('sw.js is OUT OF DATE: run node tools/build-sw.mjs'); process.exit(1); } console.log('sw.js is current (' + version + ')'); process.exit(0); }
const list = ['./', ...files.map(f => './' + f)];
fs.writeFileSync(path.join(ROOT, 'sw.js'), `// GENERATED by tools/build-sw.mjs. Do not edit by hand.
const CACHE = 'demi-plank-${version}';
const FILES = ${JSON.stringify(list)};
self.addEventListener('install', e => { e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const r = e.request; if (r.method !== 'GET') return;
  const u = new URL(r.url); if (u.origin !== location.origin) return; // never touch other sites
  // saved copy first, so a weak or hanging signal never delays a workout. A new version arrives as a whole new cache (see CACHE above).
  e.respondWith(caches.match(r, { ignoreSearch: true }).then(hit => hit || fetch(r).catch(() => (r.mode === 'navigate' ? caches.match('./index.html') : Response.error()))));
});
`);
console.log('sw.js written:', files.length, 'files, version', version);
